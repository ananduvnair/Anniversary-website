/**
 * setup.js — Run this ONCE to auto-generate photos.js from your photos folder.
 *
 * Usage:
 *   1. Drop all your photos into the  photos/  folder (any filenames, any order)
 *   2. Open a terminal in this folder (d:\our anivessary)
 *   3. Run:  node setup.js
 *   4. Done — photos.js is generated. Open index.html and gift it!
 *
 * Supported formats: jpg, jpeg, png, webp, gif, avif
 * Captions default to romantic phrases that cycle through automatically.
 */

const fs   = require('fs');
const path = require('path');

const PHOTOS_DIR = path.join(__dirname, 'photos');
const MUSIC_DIR  = path.join(__dirname, 'music');
const OUT_FILE   = path.join(__dirname, 'photos.js');

const IMAGE_EXTS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif']);
const AUDIO_EXTS = new Set(['.mp3', '.m4a', '.wav', '.ogg', '.flac', '.aac', '.mp4']);

// Romantic captions — cycle through for each photo
const CAPTIONS = [
  'The day our story began ✦',
  'Every smile, a galaxy ✦',
  'Wandering together ✦',
  'Written in the stars ✦',
  'Forever in this moment ✦',
  'You are my universe ✦',
  'Lost in you ✦',
  'Time stands still with you ✦',
  'My favourite adventure ✦',
  'Always, in every lifetime ✦',
  'Infinite love ✦',
  'You complete my sky ✦',
  'Dancing between the stars ✦',
  'My constellation ✦',
  'Everything I ever wanted ✦',
  'Home is wherever you are ✦',
  'Two stars, one orbit ✦',
  'Brighter than any sun ✦',
  'Written in stardust ✦',
  'Endlessly, always ✦',
  'My heart found its home ✦',
  'Every look, a love story ✦',
  'You make every day magical ✦',
  'Chasing sunsets with you ✦',
  'The best chapters of my life ✦',
  'You are my favourite hello ✦',
  'And still, I choose you ✦',
  'Every memory, a treasure ✦',
  'My person, always ✦',
  'Forever wouldn\'t be enough ✦',
];

// Read photos folder
let files;
try {
  files = fs.readdirSync(PHOTOS_DIR);
} catch {
  console.error('❌  Could not find the photos/ folder. Make sure it exists.');
  process.exit(1);
}

// Filter to images, sort naturally (photo1 < photo2 < photo10)
const images = files
  .filter(f => IMAGE_EXTS.has(path.extname(f).toLowerCase()))
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));

if (images.length === 0) {
  console.error('❌  No images found in photos/. Add your photos and run again.');
  process.exit(1);
}

// Build the array entries
const entries = images.map((file, i) => {
  const caption = CAPTIONS[i % CAPTIONS.length];
  // Safe JSON encoding for file paths and captions
  return `  { src: ${JSON.stringify('photos/' + file)}, caption: ${JSON.stringify(caption)} }`;
});

// Check for music file
let musicPath = 'music/song.mp3';
if (fs.existsSync(MUSIC_DIR)) {
  const musicFiles = fs.readdirSync(MUSIC_DIR).filter(f => AUDIO_EXTS.has(path.extname(f).toLowerCase()));
  if (musicFiles.length > 0) {
    musicPath = 'music/' + musicFiles[0];
  }
}

const output = `// AUTO-GENERATED by setup.js — do not edit manually.
// Run  node setup.js  again if you add or remove photos or music.

const MUSIC_SRC = ${JSON.stringify(musicPath)};

const PHOTOS = [
${entries.join(',\n')},
];
`;

fs.writeFileSync(OUT_FILE, output, 'utf8');

console.log(`✦  Done! ${images.length} photos written to photos.js`);
console.log(`✦  Music connected: ${musicPath}`);
console.log(`   Open index.html in a browser to preview.`);

